import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotRoot = resolve(packageRoot, 'spec/ebu-ograf-v1-d42afced');
export const generatedValidatorPath = resolve(packageRoot, 'src/generated/ograf-manifest-validator.ts');
const require = createRequire(import.meta.url);
const dependencySearchPaths = process.env['OGRAF_AJV_NODE_MODULES'] === undefined
    ? [packageRoot]
    : [process.env['OGRAF_AJV_NODE_MODULES']];
const ajv2020Path = require.resolve('ajv/dist/2020.js', { paths: dependencySearchPaths });
const standalonePath = require.resolve('ajv/dist/standalone/index.js', { paths: dependencySearchPaths });
const Ajv2020 = (await import(pathToFileURL(ajv2020Path).href)).default;
const standaloneCode = (await import(pathToFileURL(standalonePath).href)).default;

const schemaPaths = [
    'json-schemas/gdd/basic-types.json',
    'json-schemas/gdd/gdd-types.json',
    'json-schemas/gdd/object.json',
    'json-schemas/gdd/playout-options.json',
    'json-schemas/lib/action.json',
    'json-schemas/lib/constraints/boolean.json',
    'json-schemas/lib/constraints/number.json',
    'json-schemas/lib/constraints/string.json',
    'json-schemas/graphics/schema.json',
];

const manifestSchemaId = 'https://ograf.ebu.io/v1/specification/json-schemas/graphics/schema.json';

function readSchema(relativePath) {
    return JSON.parse(readFileSync(resolve(snapshotRoot, relativePath), 'utf8'));
}

export function generateValidatorSource() {
    const ajv = new Ajv2020({
        allErrors: true,
        strict: false,
        validateFormats: false,
        code: { esm: true, source: true, optimize: true },
    });

    for (const relativePath of schemaPaths) {
        ajv.addSchema(readSchema(relativePath));
    }
    const validate = ajv.getSchema(manifestSchemaId);
    if (validate === undefined) {
        throw new Error(`Ajv did not register ${manifestSchemaId}`);
    }

    const generated = standaloneCode(ajv, validate).replace(
        'require("ajv/dist/runtime/equal").default',
        'ografDeepEqual',
    );
    const runtimeHelpers = [
        'function ografDeepEqual(left, right) {',
        '    if (left === right) return true;',
        '    if (left === null || right === null || typeof left !== "object" || typeof right !== "object") return false;',
        '    if (Array.isArray(left) !== Array.isArray(right)) return false;',
        '    const leftKeys = Object.keys(left);',
        '    const rightKeys = Object.keys(right);',
        '    if (leftKeys.length !== rightKeys.length) return false;',
        '    return leftKeys.every((key) => Object.prototype.hasOwnProperty.call(right, key) && ografDeepEqual(left[key], right[key]));',
        '}',
    ].join('\n');
    return [
        '// @ts-nocheck',
        '/**',
        ' * Generated by scripts/generate-standalone-validator.mjs.',
        ' * Source: EBU OGraf v1 snapshot d42afcedf9348e05e35b2009b04fb9552785e35b.',
        ' * Do not edit manually; run npm run generate:validator.',
        ' */',
        runtimeHelpers,
        generated,
        '',
    ].join('\n');
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    mkdirSync(dirname(generatedValidatorPath), { recursive: true });
    writeFileSync(generatedValidatorPath, generateValidatorSource(), 'utf8');
}
